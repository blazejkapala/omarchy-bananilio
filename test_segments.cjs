const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(__dirname + '/Segments.js', 'utf8').replace('.pragma library', ''), context);
const estimate = context.estimate;
assert.equal(estimate('').segments, 0);
assert.equal(estimate('a'.repeat(160)).segments, 1);
assert.equal(estimate('a'.repeat(161)).segments, 2);
assert.equal(estimate('a'.repeat(306)).segments, 2);
assert.equal(estimate('a'.repeat(307)).segments, 3);
assert.equal(estimate('ą'.repeat(70)).segments, 1);
assert.equal(estimate('ą'.repeat(71)).segments, 2);
assert.equal(estimate('ą'.repeat(134)).segments, 2);
assert.equal(estimate('ą'.repeat(135)).segments, 3);
assert.equal(estimate('€'.repeat(80)).segments, 1);
assert.equal(estimate('€'.repeat(81)).segments, 2);
assert.equal(estimate('€'.repeat(153)).segments, 3);
assert.equal(estimate('😀'.repeat(35)).segments, 1);
assert.equal(estimate('😀'.repeat(36)).segments, 2);
assert.equal(estimate('😀'.repeat(67)).segments, 3);
assert.equal(estimate('a'.repeat(159) + 'ą').segments, 3);
assert.equal(estimate('a'.repeat(305), '+18005550101', '+12025550120').segments, 3);
assert.equal(context.withoutPolish('Zażółć gęślą jaźń! 😀'), 'Zazolc gesla jazn! 😀');
assert.equal(context.withoutPolish('ą'.normalize('NFD')), 'a');
assert.equal(context.withoutPolish('éñ€'), 'éñ€');
console.log('20 segment and Polish-text checks passed');
